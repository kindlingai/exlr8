int DEBUG_x, DEBUG_y;

RayTracer::trace(const SceneTreeNode& root, 
                 const LightList& ll,
                 const TraceParameters& tp, 
                 TraceStats& ts,
                 ostream& outs)
{
  ts._startTime = time(0);
  outs << "P6" << endl;
  outs << "# PPM file generated by the generic raytracer :)" << endl;
  outs << tp._width << " " << tp._height << " " << MAX_COLOR << endl;
  
  vector3 look = tp._lookAt - tp._eyePoint;
  look.normalize();

  double xFov, yFov;
  xFov = yFov = DEG_TO_RAD(tp._fov);

  /*
    Calculate the corresponding opposite field of view.
   */
  //  if (tp._width > tp._height)
  //  {
    xFov = atan((double)tp._width*tan(yFov/2)/tp._height)*2;
    //  }
    //  else
    //  {
    //    yFov = atan((double)tp._height*tan(xFov/2)/tp._width)*2;
    //  }

  if (DEBUG)
  {
    cerr << "Output resolution: " << tp._width << "x" << tp._height << endl;
    cerr << "hFOV = " << RAD_TO_DEG(xFov) << " degrees, vFOV = " 
         << RAD_TO_DEG(yFov) << " degrees" << endl;
  }

  /*
    Get the screen x and y vectors.  We know that:

    xg = (x - w/2) * tan(xFov/2) * 2 * look.length() / w * norm(right)
    yg = (y - h/2) * tan(yFov/2) * 2 * look.length() / h * norm(up)

    To optimize this, we precalculate 2 / w and 2 / h and put them into
    xScale and yScale.  The equations then becomes:

    xg = (xScale * x - 1) * xv
    xv = tan(xFov/2) * look.length() * norm(right)
    yg = (yScale * y - 1) * yv
    yv = tan(yFov/2) * look.length() * norm(up)
  */
  vector3 xv, yv;

  // Use the correct up and right vectors to compute xv and yv
  xv = cross(tp._up, look);
  yv = -cross(tp._right, look);
  
  xv *= (tan(xFov/2) * look.length()) / xv.length();
  yv *= (tan(yFov/2) * look.length()) / yv.length();
  
  // Get the x and y scaling factors (used to calculate gaze vector as above)
  double xScale, yScale;
  xScale = 2.0 / (double)tp._width;
  yScale = 2.0 / (double)tp._height;

  if (DEBUG)
  {
    cerr << "Root object says it is a " << root.getName() << endl;
    cerr << "Entering main loop: casting gaze rays..." << endl;
    cerr << "[";
    for (int i = 0; i < (tp._height + 19) / 20; i++)
      cerr << "=";
    cerr << "] 100%" << endl;
    cerr << "[";
  }

  Ray gaze;
  Intersection intr;
  gaze._start = tp._eyePoint;
  for (int y = 0; y < tp._height; y++)
  {
    DEBUG_y = y;
    if (DEBUG)
      if (y % 20 == 0)
        cerr << "*";
    for (int x = 0; x < tp._width; x++)
    {
      DEBUG_x = x;
      vector3 color(0, 0, 0);
      for (int i = 0; i < tp._oversampling; i++)
      {
        /* Trace the gaze ray originating from the eyepoint 
           through the viewport */
        if (tp._oversampling <= 1) 
        {
          gaze._direction = (xScale * x - 1) * xv 
            + (1 - yScale * y) * yv 
            + look;
        }
        else
        {
          double dx = double(rand() % 800) / 1000 - 0.4;
          double dy = double(rand() % 800) / 1000 - 0.4;
          gaze._direction = (xScale * ((double)x + dx) - 1) * xv 
            + (1 - yScale * ((double)y + dy)) * yv 
            + look;          
        }
        gaze._direction.normalize();

        ts._raysCasted++;
        
        IntersectionList il;
        if (root.getIntersection(gaze, il))
        {
          IntersectionList::iterator closest = il.begin();
          IntersectionList::iterator i;
          for (i = il.begin(); i < il.end(); i++)
          {
            if (i->_distance < closest->_distance)
              closest = i;
          }
          closest->_originalRay = gaze;
          vector<double> interiorStack;
          interiorStack.push_back(DEFAULT_IOR);
          closest->_object->getColor(root, ll, *closest, interiorStack, color);
        }
      }
        /*
          double max = (color[0] > color[1] && color[0] > color[2]) ? color[0] : 
          ((color[1] > color[2]) ? color[1] : color[2]);
          if (max > 1.0)
          color = color / max;*/
      
      // Clamp colors
      if (color[0] > 1.0)
        color[0] = 1;
      if (color[1] > 1.0)
        color[1] = 1;
      if (color[2] > 1.0)
        color[2] = 1;
      color = color * MAX_COLOR / tp._oversampling;
      outs << (char)(color[0]) << (char)(color[1]) << (char)(color[2]);
    }
  }
  ts._endTime = time(0);
  if (DEBUG) 
  {
    cerr << "] done." << endl;
    cerr << ts._raysCasted << " rays cast in " 
         << ts._endTime - ts._startTime << " seconds ("
         << int(ts._raysCasted / (ts._endTime - ts._startTime)) 
         << " rays per second)" 
         << endl;
  }
}

